void FakeStrip::setRealtimePixelColor(unsigned pixel, uint32_t color) {
  if (pixel >= length) return;
  ++realtimeWrites;
  if (!BusManager::canAllShow()) ++paintsDuringTx;
  nowUs += pixelUs;
  logical[pixel] = {byte(color >> 24), byte(color >> 16), byte(color >> 8)};
  if (duringPaint) {
    auto hook = std::move(duringPaint);
    duringPaint = nullptr;
    hook();
  }
}

void FakeStrip::show() {
  if (suspendBeforeShow) suspended = true;
  if (rejectShow || !actualShowPrefix()) return;
  nowUs += paintUs;
  if (editing.size() != length * 3) editing.assign(length * 3, 0);
  for (size_t logicalIndex = 0; logicalIndex < length; ++logicalIndex) {
    const auto physical = map[logicalIndex];
    editing[physical * 3] = logical[logicalIndex][0];
    editing[physical * 3 + 1] = logical[logicalIndex][1];
    editing[physical * 3 + 2] = logical[logicalIndex][2];
  }
  actualShowSuffix();
  lastShowMs = millis();
}

