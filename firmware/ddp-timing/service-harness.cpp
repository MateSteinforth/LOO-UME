static void overlapPaintsDuringTransmission() {
  setup(true);
  assert(stat("overlap_requested") == 1 && stat("overlap_active") == 1);
  const auto completedBefore = stat("tx_completed");
  const auto presentedBefore = stat("presented");
  strip.paintUs = 3000;
  receiveFrame(0x20, 21);
  notificationPrefix(false);
  const uint32_t firstStart = strip.txStartUs.back();
  assert(firstStart == 3000);
  advance(5000);
  receiveFrame(0x21, 21);
  notificationPrefix(false);
  // The second frame is painted during the first transmission and starts when it ends.
  assert(strip.wireSnapshots.size() == 2 && strip.driverWaits == 1);
  assert(uniform(strip.wireSnapshots[0], 0x20) && uniform(strip.wireSnapshots[1], 0x21));
  assert(strip.txStartUs[1] == firstStart + WireUs);
  assert(strip.paintsDuringTx == strip.length);
  assert(stat("timing.overlapped") == 1 && stat("tx_completed") == completedBefore + 1);
  assert(stat("timing.latency.max_us") == firstStart + WireUs - 8000);
  advance(WireUs);
  notificationPrefix(false);
  assert(stat("tx_completed") == completedBefore + 2 && stat("presented") == presentedBefore + 2);
}

