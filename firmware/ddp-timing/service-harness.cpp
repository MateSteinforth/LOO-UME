namespace BusManager {
bool canAllShow() { return uint32_t(nowUs - busyUntilUs) < 0x80000000u; }
// NeoEsp32RmtXMethod::Update(): wait for the active transmission, send the editing buffer, then swap.
void show() {
  if (!canAllShow()) {
    ++strip.driverWaits;
    nowUs = busyUntilUs;
  }
  // Nothing may write the buffer of the frame that is on the wire.
  if (!strip.wireSnapshots.empty()) assert(strip.sending == strip.wireSnapshots.back());
  std::swap(strip.editing, strip.sending);
  strip.wireSnapshots.push_back(strip.sending);
  strip.txStartUs.push_back(nowUs);
  busyUntilUs = nowUs + WireUs;
}
size_t getNumBusses() { return busses.size(); }
Bus* getBus(size_t index) { return index < busses.size() ? &busses[index] : nullptr; }
}

