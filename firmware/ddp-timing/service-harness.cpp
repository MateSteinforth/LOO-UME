static std::vector<uint8_t> packet(size_t offset, size_t count, uint8_t sequence,
                                   bool push, uint8_t value) {
  std::vector<uint8_t> bytes(10 + count, value);
  bytes[0] = push ? 0x41 : 0x40;
  bytes[1] = sequence;
  bytes[2] = 0x0b;
  bytes[3] = 1;
  bytes[4] = byte(offset >> 24);
  bytes[5] = byte(offset >> 16);
  bytes[6] = byte(offset >> 8);
  bytes[7] = byte(offset);
  bytes[8] = byte(count >> 8);
  bytes[9] = byte(count);
  return bytes;
}

static void receiveFrame(uint8_t value, uint32_t sender, bool push = true,
                         size_t omitOffset = SIZE_MAX) {
  uint8_t sequence = 1;
  const size_t total = strip.length * 3;
  for (size_t offset = 0; offset < total; offset += 1440) {
    const size_t count = std::min<size_t>(1440, total - offset);
    if (offset != omitOffset) {
      auto bytes = packet(offset, count, sequence, push && offset + count == total, value);
      handleDDPPacket(reinterpret_cast<e131_packet_t*>(bytes.data()), bytes.size(), IPAddress(sender));
    }
    sequence = sequence == 15 ? 1 : uint8_t(sequence + 1);
  }
}

static std::array<uint8_t, 3> indexedRgb(size_t logical) {
  return {uint8_t(logical), uint8_t(logical >> 8), uint8_t(0xa5 ^ logical)};
}

static void receiveIndexedFrame(uint32_t sender) {
  uint8_t sequence = 1;
  const size_t total = strip.length * 3;
  for (size_t offset = 0; offset < total; offset += 1440) {
    const size_t count = std::min<size_t>(1440, total - offset);
    auto bytes = packet(offset, count, sequence, offset + count == total, 0);
    for (size_t byteIndex = 0; byteIndex < count; byteIndex += 3) {
      const auto color = indexedRgb((offset + byteIndex) / 3);
      bytes[10 + byteIndex] = color[0];
      bytes[10 + byteIndex + 1] = color[1];
      bytes[10 + byteIndex + 2] = color[2];
    }
    handleDDPPacket(reinterpret_cast<e131_packet_t*>(bytes.data()), bytes.size(), IPAddress(sender));
    sequence = sequence == 15 ? 1 : uint8_t(sequence + 1);
  }
}

static void notificationPrefix(bool nativeDue = true) {
  actualNotificationPrefix();
  if (nativeDue && (realtimeMode != REALTIME_MODE_DDP || realtimeOverride)) {
    ++strip.nativeServices;
    strip.show();
  }
}

static uint32_t stat(const std::string& key) {
  jsonValues.clear();
  looDdpJson({});
  const auto value = jsonValues.find("loo_ddp." + key);
  assert(value != jsonValues.end());
  return value->second;
}

static bool uniform(const std::vector<byte>& wire, byte value) {
  return std::all_of(wire.begin(), wire.end(), [value](byte item) { return item == value; });
}

static void setup(bool overlap = false) {
  looDdpReset();
  looDdpControl(overlap ? 1 : 0, true);
  nowUs = 0;
  busyUntilUs = 0;
  exits = 0;
  realtimeMode = REALTIME_MODE_INACTIVE;
  realtimeOverride = REALTIME_OVERRIDE_NONE;
  realtimeTimeout = 0;
  realtimeTimeoutMs = 1000;
  useMainSegmentOnly = true;
  busses = {{704}, {640}, {640}, {640}};
  strip = {};
  strip.length = 2624;
  strip.logical.assign(strip.length, {0, 0, 0});
  strip.editing.assign(strip.length * 3, 0);
  strip.sending.assign(strip.length * 3, 0);
  strip.map.resize(strip.length);
  for (size_t i = 0; i < strip.length; ++i) strip.map[i] = uint16_t((i * 733) % strip.length);
  loo_dma_requested = 0;
  loo_dma_active_lanes = 0;
  loo_dma_failure = 0;
  DMXAddress = 0;
  arlsOffset = 0;
  jsonValues.clear();
  // The current service configures storage before the UDP receiver runs.
  looDdpService();
}

static void advance(uint32_t us) { nowUs += us; }

// Runs a main loop with a 1 ms period. Frames arrive at their due times or after a blocking show.
static void runSchedule(const std::vector<uint32_t>& due, uint32_t endUs, uint32_t sender) {
  size_t next = 0;
  uint8_t value = 1;
  while (nowUs < endUs) {
    while (next < due.size() && due[next] <= nowUs) {
      receiveFrame(value++, sender);
      ++next;
    }
    notificationPrefix(false);
    advance(1000);
  }
}

// Every transmission is one complete frame, frames stay in order, and transmissions never overlap.
static void checkWire() {
  for (size_t i = 0; i < strip.wireSnapshots.size(); ++i) {
    const byte value = strip.wireSnapshots[i][0];
    assert(uniform(strip.wireSnapshots[i], value));
    if (!i) continue;
    assert(value > strip.wireSnapshots[i - 1][0]);
    assert(strip.txStartUs[i] >= strip.txStartUs[i - 1] + WireUs);
  }
}

static unsigned burstRun(bool overlap) {
  setup(overlap);
  strip.paintUs = 8000;
  // Three frames 5 ms apart every 100 ms: 30 frames/s on average, with network bunching.
  std::vector<uint32_t> due;
  for (uint32_t burst = 0; burst < 10; ++burst)
    for (uint32_t offset : {0u, 5000u, 10000u}) due.push_back(burst * 100000 + offset);
  runSchedule(due, 1100000, 26);
  checkWire();
  return unsigned(strip.wireSnapshots.size());
}

