static void overloadKeepsLatencyBounded() {
  // Frames every 15 ms exceed the 21.42 ms wire time; the newest frame wins and latency stays bounded.
  setup(true);
  strip.paintUs = 3000;
  std::vector<uint32_t> due;
  for (uint32_t frame = 0; frame < 134; ++frame) due.push_back(frame * 15000);
  runSchedule(due, 2000000, 29);
  checkWire();
  const auto shown = unsigned(strip.wireSnapshots.size());
  assert(shown >= 85 && stat("timing.presented") == shown);
  assert(stat("timing.latency.max_us") <= 2 * WireUs + strip.paintUs + 1000);
  assert(stat("timing.replaced_loop") + stat("timing.replaced_paint") > 0);
}

static void histogramsMatchSchedule() {
  setup();
  strip.paintUs = 5000;
  strip.pixelUs = 1;
  // Start after time zero: the receiver treats a zero completion time as "no previous frame".
  std::vector<uint32_t> due;
  for (uint32_t frame = 0; frame < 31; ++frame) due.push_back(1000 + frame * 33000);
  runSchedule(due, 1000 + 31 * 33000, 30);
  assert(stat("timing.complete") == 31 && stat("timing.presented") == 31);
  assert(stat("timing.edges_us[0]") == 500 && stat("timing.edges_us[16]") == 100000);
  assert(jsonValues.count("loo_ddp.timing.loop.bins[17]") == 1);
  assert(jsonValues.count("loo_ddp.timing.loop.bins[18]") == 0);
  // Bins: 0 <= 500, 1 <= 1000, 3 <= 4000, 4 <= 6000, 5 <= 8000, 9 <= 24000, 12 <= 36000 us.
  assert(stat("timing.arrival.n") == 30 && stat("timing.arrival.bins[12]") == 30);
  assert(stat("timing.assembly.bins[0]") == 31);
  assert(stat("timing.wait_idle.bins[0]") == 31 && stat("timing.wait_busy.n") == 0);
  assert(stat("timing.paint.bins[3]") == 31 && stat("timing.paint.avg_us") == 2624);
  assert(stat("timing.show.bins[4]") == 31 && stat("timing.show.max_us") == 5000);
  assert(stat("timing.latency.bins[5]") == 31 && stat("timing.latency.max_us") == 7624);
  assert(stat("timing.present.n") == 30 && stat("timing.present.bins[12]") == 30);
  assert(stat("timing.wire.n") == 31 && stat("timing.wire.bins[9]") == 31);
  assert(stat("timing.wire.max_us") == 22000);
  assert(stat("timing.loop.n") > 0 && stat("timing.loop.bins[1]") == stat("timing.loop.n"));
  assert(stat("timing.replaced_loop") + stat("timing.replaced_wire") + stat("timing.replaced_paint") == 0);
  assert(stat("timing.overlapped") == 0 && stat("timing.wire_estimate_us") == WireUs);

  // A reset clears timing and keeps the selected mode.
  looDdpControl(1, false);
  looDdpControl(-1, true);
  assert(stat("timing.presented") == 0 && stat("timing.paint.n") == 0 && stat("overlap_requested") == 1);
  looDdpControl(0, false);
  assert(stat("overlap_requested") == 0);
}

